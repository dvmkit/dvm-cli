function sdkPresentationImports(source: string): string[] {
  const parsed = ts.createSourceFile("caller.ts", source, ts.ScriptTarget.Latest, true);
  const violations: string[] = [];
  const sdkModule = (node: ts.Node | undefined): boolean =>
    !!node && ts.isStringLiteral(node) && node.text === "@dvmkit/sdk/internal";
  const check = (symbol: string): void => {
    if (callerSymbols.has(symbol)) violations.push(symbol);
  };
  function visit(node: ts.Node): void {
    if (ts.isImportDeclaration(node) && sdkModule(node.moduleSpecifier)) {
      const bindings = node.importClause?.namedBindings;
      if (bindings && ts.isNamespaceImport(bindings)) violations.push("namespace import");
      if (bindings && ts.isNamedImports(bindings)) {
        for (const specifier of bindings.elements) check((specifier.propertyName ?? specifier.name).text);
      }
    }
    if (ts.isExportDeclaration(node) && sdkModule(node.moduleSpecifier)) {
      if (!node.exportClause || ts.isNamespaceExport(node.exportClause)) violations.push("namespace export");
      else for (const specifier of node.exportClause.elements) check((specifier.propertyName ?? specifier.name).text);
    }
    if (ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument) && sdkModule(node.argument.literal) && node.qualifier) {
      check(node.qualifier.getText(parsed).split(".")[0]);
    }
    if (ts.isVariableDeclaration(node) && ts.isObjectBindingPattern(node.name)) {
      const initializer = node.initializer && ts.isAwaitExpression(node.initializer) ? node.initializer.expression : node.initializer;
      if (initializer && ts.isCallExpression(initializer) && initializer.expression.kind === ts.SyntaxKind.ImportKeyword && sdkModule(initializer.arguments[0])) {
        for (const element of node.name.elements) check((element.propertyName ?? element.name).getText(parsed));
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(parsed);
  return violations;
}

function sourceFiles(directory: string): string[] {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? (["__tests__", "test-support"].includes(entry.name) ? [] : sourceFiles(path)) : entry.name.endsWith(".ts") ? [path] : [];
  });
}

describe("caller module ownership", () => {
  it("keeps production imports on the caller implementations", () => {
    const violations = sourceFiles(join(import.meta.dirname, "../src")).flatMap((path) =>
      sdkPresentationImports(readFileSync(path, "utf8")).map((symbol) => `${path}: ${symbol}`)
    );
    expect(violations).toEqual([]);
  });

  it("rejects SDK presentation imports including aliases and type imports", () => {
    expect(sdkPresentationImports('import { buildPolicy as policy, type NextAction } from "@dvmkit/sdk/internal";')).toEqual(["buildPolicy", "NextAction"]);
    expect(sdkPresentationImports('import { fundCredit as fund, type CreditPlan, enforceGlobalBudget } from "@dvmkit/sdk/internal";')).toEqual(["fundCredit", "CreditPlan", "enforceGlobalBudget"]);
    expect(sdkPresentationImports('const { fundCredit: fund, loadConfig } = await import("@dvmkit/sdk/internal");')).toEqual(["fundCredit", "loadConfig"]);
    expect(sdkPresentationImports('type Plan = import("@dvmkit/sdk/internal").CreditPlan; export { loadFloat } from "@dvmkit/sdk/internal";')).toEqual(["CreditPlan", "loadFloat"]);
    expect(sdkPresentationImports('import * as sdk from "@dvmkit/sdk/internal";')).toEqual(["namespace import"]);
    expect(sdkPresentationImports('import { prepareAgentSpend as prepare, type PendingSubmissionContext, recoverPendingSubmission } from "@dvmkit/sdk/internal";')).toEqual(["prepareAgentSpend", "recoverPendingSubmission"]);
    expect(sdkPresentationImports('import { info, fundingRailLabel, type JobPolicy } from "@dvmkit/sdk/internal";')).toEqual(["info", "fundingRailLabel"]);
  });
});
